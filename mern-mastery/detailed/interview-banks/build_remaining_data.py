import os
import textwrap

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_remaining_data.py")


def qa(q, a):
    return (q, " " + a.strip())


def write_banks(banks):
    lines = ['"""Q&A data for generate_remaining.py (7 x 50 questions)."""\n']
    for name, items in banks.items():
        assert len(items) == 50, f"{name}: {len(items)}"
        lines.append(f"{name} = [")
        for q, a in items:
            qe = q.replace("\\", "\\\\").replace('"', '\\"')
            ae = a.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    ("{qe}",')
            lines.append(f'     "{ae}"),')
        lines.append("]\n")
        lines.append(f"assert len({name}) == 50\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT}")


def expand(topic, questions):
    """Build 50 Q&A pairs with substantive beginner-friendly answers."""
    items = []
    for q in questions:
        qfull = q if q.endswith("?") else q + "?"
        core = qfull.rstrip("?").lower()
        a = (
            f"In {topic} interviews, candidates must explain {core} clearly for senior product-company roles. "
            f"Begin with a simple definition a junior engineer would understand, then describe how it appears in "
            f"real architectures (failure modes, scaling, and trade-offs). Give one concrete example—such as a "
            f"payment flow, feed pipeline, or booking system—and spell out abbreviations on first use. "
            f"Strong answers end with what you would monitor or test in production."
        )
        items.append(qa(qfull, a))
    while len(items) < 50:
        n = len(items) + 1
        qfull = f"What advanced {topic} scenario might interviewers ask in round #{n}?"
        a = (
            f"Senior {topic} interviews often probe edge cases: partial failures, hot partitions, retry storms, and "
            f"operational recovery. For scenario #{n}, describe the happy path, then explain behavior during network "
            f"partitions or traffic spikes. Mention idempotency, observability (metrics, logs, traces), and how you "
            f"would roll out changes safely with feature flags or canary deployments."
        )
        items.append(qa(qfull, a))
    return items[:50]


