qa("What is cache eviction and name common policies?", "Eviction removes entries when cache is full. Least Recently Used (LRU) evicts oldest accessed item. Least Frequently Used (LFU) evicts least popular. First In First Out (FIFO) evicts oldest inserted. Time To Live (TTL) expires by time. LRU is most common."),
